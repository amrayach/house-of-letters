#!/usr/bin/env node
/**
 * Generates src/data/paperDates.js from src/data/diary_index_001_048.csv.
 *
 * CSV quirks handled: UTF-8 BOM, CRLF, `;`-separated date tokens, mixed
 * `/` and `-` separators (`11/10/88`, `12-1-90`), day-ranges (`25-26/2/89`),
 * out-of-order tokens (range = min/max of all parsed dates, not first/last).
 *
 * Regenerate with: node scripts/generate-paper-dates.cjs
 */
const fs = require('fs');
const path = require('path');

const CSV_PATH = path.join(__dirname, '..', 'src', 'data', 'diary_index_001_048.csv');
const OUT_PATH = path.join(__dirname, '..', 'src', 'data', 'paperDates.js');
const MAX_PAPER_ID = 46; // papers rendered in the archive (letters.json has 46)

// Known CSV data errors, confirmed against scripts/exhibition-papers.js (the
// client-reviewed exhibition data). Paper 33 contains a stray `6-6-92` token
// and paper 45 a stray `20-7-92` token, both out of sequence; the exhibition
// lists 33 as ending 8/3/1992 and 45 as ending 23/6/1992. Paper 40's
// `23-4-93`/`26-4-93` tokens are `93`→`92` year typos (they sit between
// `13-4-92` and `30-4-92`, and neighboring papers bracket it as
// 8/4/1992 – 1/5/1992); true range 8/4/1992 – 1/5/1992.
// PENDING CLIENT VERIFICATION (all three) — see spec §13.
const END_OVERRIDES = { 33: '8/3/1992', 40: '1/5/1992', 45: '23/6/1992' };

function parseToken(token) {
  // Extract all integers; last = 2-digit year, second-to-last = month,
  // any remaining leading integers are day(s) (day-ranges yield several).
  const nums = (token.match(/\d+/g) || []).map(Number);
  if (nums.length < 3) return [];
  const rawYear = nums[nums.length - 1];
  const year = rawYear > 100 ? rawYear : 1900 + rawYear;
  const month = nums[nums.length - 2];
  if (month < 1 || month > 12) return [];
  return nums
    .slice(0, -2)
    .filter((day) => day >= 1 && day <= 31)
    .map((day) => ({ day, month, year, time: Date.UTC(year, month - 1, day) }));
}

function formatDate({ day, month, year }) {
  return `${day}/${month}/${year}`;
}

const raw = fs.readFileSync(CSV_PATH, 'utf8').replace(/^﻿/, '');
const lines = raw.split(/\r?\n/).filter((line) => line.trim() && !line.startsWith('#'));
const entries = {};

for (const line of lines) {
  const commaIdx = line.indexOf(',');
  const id = Number(line.slice(0, commaIdx));
  if (!Number.isInteger(id) || id < 1 || id > MAX_PAPER_ID) continue;
  const dates = line
    .slice(commaIdx + 1)
    .split(/[;–]/)
    .flatMap(parseToken)
    .sort((a, b) => a.time - b.time);
  if (!dates.length) continue;
  const start = formatDate(dates[0]);
  const end = END_OVERRIDES[id] || formatDate(dates[dates.length - 1]);
  entries[id] = { start, end, label: start === end ? start : `${start} – ${end}` };
}

const banner = `// AUTO-GENERATED by scripts/generate-paper-dates.cjs — do not edit by hand.
// Source: src/data/diary_index_001_048.csv (real diary dates per paper).
// Regenerate with: node scripts/generate-paper-dates.cjs
`;
const body = `export const PAPER_DATES = Object.freeze({\n${Object.entries(entries)
  .map(([id, e]) => `  ${id}: Object.freeze({ start: '${e.start}', end: '${e.end}', label: '${e.label}' }),`)
  .join('\n')}\n});\n`;

fs.writeFileSync(OUT_PATH, banner + body);
console.log(`Wrote ${Object.keys(entries).length} paper date entries to ${OUT_PATH}`);
